import React from 'react';
import { MODEL_ORDER, MODEL_LABELS } from '../models/conviction.js';
import { renderMarkdown } from '../lib/markdown.jsx';
import { WHARTON_BADGE } from '../config.js';

/** Badge shown wherever the no-AI mode is active. */
export function MathModeBadge() {
  return <span className="pill bg-accent/15 text-accent border border-accent/40">{WHARTON_BADGE}</span>;
}

/**
 * Standard mode: AI explanation generated from computed metrics only.
 * `fallback` (array of paragraphs) is shown quietly if the AI call fails, so a reader never sees a dead end.
 */
export function StandardReasoning({ state, onGenerate, canGenerate, fallback }) {
  return (
    <section className="card p-4 md:p-5" id="reasoning">
      <header className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h2 className="font-semibold">AI-generated reasoning</h2>
          <p className="text-xs text-muted">Generated by {state.model || 'Claude Sonnet'} from the computed metrics and subscores only. No raw market data or filings are sent; the model is instructed not to invent figures.</p>
        </div>
        <button className="btn" disabled={!canGenerate || state.status === 'loading'} onClick={onGenerate}>
          {state.status === 'loading' ? 'Generating…' : state.text ? 'Regenerate' : 'Generate explanation'}
        </button>
      </header>
      {state.status === 'loading' && (
        <div className="mt-4 flex items-center gap-3 text-sm text-ink-2">
          <span className="inline-block w-4 h-4 border-2 border-s1 border-t-transparent rounded-full animate-spin" /> Asking Claude…
        </div>
      )}
      {state.status === 'error' && (
        <div className="mt-4">
          <div className="text-xs text-muted mb-2">The AI explanation is unavailable right now ({state.error}). Here is the plain-English summary computed from the numbers instead:</div>
          {fallback && fallback.length ? <div className="space-y-2 text-sm text-ink-2 leading-relaxed">{fallback.map((p, i) => <p key={i}>{p}</p>)}</div> : null}
        </div>
      )}
      {state.status === 'done' && state.text && <div className="md mt-2 text-sm">{renderMarkdown(state.text)}</div>}
      {state.status === 'idle' && !canGenerate && <div className="mt-3 text-sm text-muted">Run an analysis first.</div>}
    </section>
  );
}

/** Wharton ("Show the math") mode: deterministic, formula-by-formula templates. No AI anywhere. */
export function WhartonReasoning({ results, conviction }) {
  return (
    <section className="card p-4 md:p-5" id="reasoning">
      <header className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h2 className="font-semibold">Methodology</h2>
          <p className="text-xs text-muted">Every number below is computed in the browser from the listed inputs. Fixed templates; nothing is generated. Use "Export PDF" at the top for the PDF.</p>
        </div>
        <MathModeBadge />
      </header>

      {conviction && conviction.score !== null && (
        <div className="mt-5">
          <h3 className="text-sm font-semibold">Conviction score</h3>
          <table className="steps-table mt-2">
            <thead><tr><th>Step</th><th>Formula</th><th>Calculation</th><th>Result</th></tr></thead>
            <tbody>
              <tr>
                <td>Weighted average</td>
                <td className="num">score = Σ wᵢ·sᵢ / Σ wᵢ</td>
                <td className="num">({conviction.breakdown.map((b) => `${b.weight}×${b.subscore}`).join(' + ')}) / {conviction.sumWeights}</td>
                <td className="num">{conviction.score} → {conviction.label}</td>
              </tr>
              {conviction.excluded.length > 0 && (
                <tr>
                  <td>Excluded models</td>
                  <td>re-normalized over available models</td>
                  <td>{conviction.excluded.map((e) => `${MODEL_LABELS[e.id]} (${e.reason})`).join('; ')}</td>
                  <td>—</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      )}

      <div className="mt-6 space-y-7">
        {MODEL_ORDER.map((id) => {
          const r = results[id];
          if (!r) return null;
          return (
            <div key={id} id={`method-${id}`}>
              <div className="flex items-baseline justify-between gap-3">
                <h3 className="text-sm font-semibold">{MODEL_LABELS[id]}</h3>
                <span className="num text-sm text-ink-2">{r.available ? `subscore ${r.subscore}` : 'unavailable'}</span>
              </div>
              {!r.available ? (
                <p className="text-sm text-bad mt-1">{r.error}</p>
              ) : (
                <>
                  <p className="text-xs text-muted mt-1">{r.note}</p>
                  <div className="mt-2 text-xs">
                    <span className="text-muted">Inputs: </span>
                    {r.inputs.map((inp, i) => (
                      <span key={i} className="text-ink-2">{inp.label} = <span className="num text-ink">{inp.value}</span> ({inp.source}){i < r.inputs.length - 1 ? '; ' : ''}</span>
                    ))}
                  </div>
                  <div className="overflow-x-auto mt-2">
                    <table className="steps-table">
                      <thead><tr><th>Step</th><th>Formula</th><th>Calculation</th><th>Result</th></tr></thead>
                      <tbody>
                        {r.steps.map((s, i) => (
                          <tr key={i}>
                            <td className="text-ink-2 whitespace-nowrap">{s.label}</td>
                            <td className="num text-ink-2">{s.formula}</td>
                            <td className="num text-ink-2">{s.calc}</td>
                            <td className="num text-ink font-semibold whitespace-nowrap">{s.result}</td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                  <div className="text-xs text-muted mt-2">Scoring rule: {r.scoringRule}</div>
                </>
              )}
            </div>
          );
        })}
      </div>
    </section>
  );
}
